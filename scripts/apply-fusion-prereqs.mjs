#!/usr/bin/env node
/**
 * Apply the fusion requirement rules from scripts/lib/fusion-prereqs.mjs:
 * every fusion needs two normal skills of its own tier or one below, and
 * fusions whose theme had to change get their rewritten name/description.
 * Rewrites data/skills-data.js and data/career-fusions-skills-data.js.
 * Run via build-data.mjs (after generate-careers.mjs) or on its own.
 */
import fs from 'fs'
import path from 'path'
import vm from 'vm'
import { fileURLToPath } from 'url'
import { FUSION_PREREQS, FUSION_REWRITES } from './lib/fusion-prereqs.mjs'
import { resolveActivationEffectsForSkill } from './lib/resolve-activation-effects.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const dataDir = path.join(root, 'data')

function loadWindowExport(file, exportName) {
  const sandbox = { window: {} }
  vm.createContext(sandbox)
  vm.runInContext(fs.readFileSync(path.join(dataDir, file), 'utf8'), sandbox)
  return sandbox.window[exportName]
}

function applyTo(lists) {
  let changed = 0
  const rewritten = []
  for (const list of lists) {
    for (const skill of list || []) {
      const prereqs = FUSION_PREREQS[skill.id]
      if (prereqs) {
        const next = { type: 'AND', skills: [...prereqs] }
        if (JSON.stringify(skill.prerequisites) !== JSON.stringify(next)) {
          skill.prerequisites = next
          changed += 1
        }
      }
      const rewrite = FUSION_REWRITES[skill.id]
      if (rewrite) {
        if (rewrite.name) skill.name = rewrite.name
        if (rewrite.desc && skill.desc !== rewrite.desc) {
          skill.desc = rewrite.desc
          rewritten.push(skill)
        }
      }
    }
  }
  return { changed, rewritten }
}

// ── skills-data.js (all fusion lists except career_fusion) ──
const skillsPath = path.join(dataDir, 'skills-data.js')
const skills = loadWindowExport('skills-data.js', 'SKILLS_DATA')
const main = applyTo(Object.values(skills.fusion || {}))
{
  const raw = fs.readFileSync(skillsPath, 'utf8')
  const marker = 'const SKILLS_DATA ='
  const header = raw.slice(0, raw.indexOf(marker))
  fs.writeFileSync(skillsPath, `${header}${marker} ${JSON.stringify(skills, null, 4)};\n\nwindow.SKILLS_DATA = SKILLS_DATA;\n`, 'utf8')
}

// ── career-fusions-skills-data.js (generated by generate-careers.mjs) ──
const careerPath = path.join(dataDir, 'career-fusions-skills-data.js')
const careerFusions = loadWindowExport('career-fusions-skills-data.js', 'CAREER_FUSIONS_DATA')
const career = applyTo(Object.values(careerFusions || {}))
if (career.rewritten.length) {
  const effects = JSON.parse(fs.readFileSync(path.join(dataDir, 'json', 'effects.json'), 'utf8'))
  for (const skill of career.rewritten) {
    const resolved = resolveActivationEffectsForSkill(skill, effects, {})
    if (resolved.length) skill.activationEffects = resolved
    else delete skill.activationEffects
  }
}
fs.writeFileSync(careerPath, `// Auto-generated by scripts/generate-careers.mjs — do not edit by hand\nconst CAREER_FUSIONS_DATA = ${JSON.stringify(careerFusions, null, 4)}\n\nif (typeof window !== 'undefined') {\n  window.CAREER_FUSIONS_DATA = CAREER_FUSIONS_DATA\n}\n`, 'utf8')

console.log(`Fusion requirements: ${main.changed + career.changed} updated, ${main.rewritten.length + career.rewritten.length} descriptions rewritten`)
